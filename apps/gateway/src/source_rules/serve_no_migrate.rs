//! `serve` and the container entrypoint never migrate or bootstrap (AGENTS.md
//! invariant and Deployment rule, #591). The Dockerfiles and the Helm chart
//! are checked by `tests/entrypoint-no-migrate.test.mjs` and
//! `tests/helm-chart.test.mjs`; this module checks the Rust side:
//!
//! 1. nothing reachable from `serve` (commands/serve.rs) names a *sink*: a
//!    function that applies migrations (`Store::migrate_enterprise`), applies
//!    runtime grants, seeds or provisions (`bootstrap::seed`,
//!    `bootstrap::provision_user`, `demo::seed`, `demo::add_missing_personas`),
//!    or one of the `commands.rs` entry points of those. Reachability is a
//!    call graph over the whole production build (lib and binary), resolved by
//!    *name* and call shape: a method call `x.run()` reaches every method
//!    called `run`, a bare call `run()` every free function of that name, a
//!    path call `T::run()` both; library code cannot reach the binary. The
//!    graph over-approximates (same-named methods are merged), so a false
//!    path is possible; it would then be fixed or reasoned about, never
//!    ignored;
//! 2. the `Command::Serve` arm of `commands::dispatch` calls only `serve`;
//! 3. the code every command runs before dispatch (`main`, `run` in
//!    main.rs) and the statements of `dispatch` outside its `match` call no
//!    sink;
//! 4. no string literal reachable from `serve` is a bare CLI subcommand name
//!    of a sink (`"migrate"`, `"grants"`, ...), which would be a re-exec.
//!
//! Sinks are found two ways so a rename cannot hide one: the explicit list
//! [`SINKS`] (each must still exist), and any function that calls `.run` on
//! `MIGRATOR` or invokes `migrate!` (discovered; `migrate_enterprise` must be
//! among them).
//!
//! Cannot see: calls reached only through function pointers or closures
//! stored in data and called under another name; code generated by a
//! procedural macro; a `macro_rules!` invoked with its own name hidden in a
//! path; SQL or a database function that migrates; another process. Calls
//! made in dependencies are out of scope.
use std::collections::{BTreeMap, BTreeSet, VecDeque};

use proc_macro2::{Delimiter, TokenStream, TokenTree};
use syn::{ext::IdentExt, visit::Visit};

use super::tree::Source;

/// (file, function): the functions that migrate, grant, seed or provision.
const SINKS: &[(&str, &str)] = &[
    ("store.rs", "migrate_enterprise"),
    ("store.rs", "apply_runtime_grants"),
    ("bootstrap.rs", "seed"),
    ("bootstrap.rs", "provision_user"),
    ("demo.rs", "seed"),
    ("demo.rs", "add_missing_personas"),
    ("commands.rs", "migrate"),
    ("commands.rs", "grants"),
    ("commands.rs", "bootstrap_dev"),
    ("commands.rs", "bootstrap_demo"),
    ("commands.rs", "provision_user"),
];

/// The CLI subcommand names of the sinks.
const SUBCOMMANDS: &[&str] = &[
    "migrate",
    "grants",
    "bootstrap-dev",
    "bootstrap-demo",
    "provision-user",
];

const ENTRY: (&str, &str) = ("commands/serve.rs", "serve");

type Key = (String, String);

/// How a function is called.
#[derive(Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Debug)]
enum Call {
    /// `f(..)`
    Bare,
    /// `x.f(..)`
    Method,
    /// `T::f(..)`, `module::f(..)`, or such a path used as a value.
    Path,
}

#[derive(Default, Clone)]
struct Body {
    calls: BTreeSet<(Call, String)>,
    strings: BTreeSet<String>,
    /// Discovered as a sink (runs the migrator).
    migrates: bool,
}

impl Body {
    fn absorb(&mut self, other: &Body) {
        self.calls.extend(other.calls.iter().cloned());
        self.strings.extend(other.strings.iter().cloned());
        self.migrates |= other.migrates;
    }

    fn names(&self) -> BTreeSet<String> {
        self.calls.iter().map(|(_, n)| n.clone()).collect()
    }
}

#[derive(Default)]
struct Node {
    body: Body,
    free: bool,
    method: bool,
    bin: bool,
}

#[derive(Default)]
pub(super) struct Graph {
    /// Every function and method, merged by (file, name).
    fns: BTreeMap<Key, Node>,
    by_name: BTreeMap<String, Vec<Key>>,
    macros: BTreeMap<String, Body>,
}

fn is_punct(token: Option<&TokenTree>, c: char) -> bool {
    matches!(token, Some(TokenTree::Punct(p)) if p.as_char() == c)
}

fn tokens_into(tokens: TokenStream, macros: &BTreeMap<String, Body>, body: &mut Body) {
    let all: Vec<TokenTree> = tokens.into_iter().collect();
    for (at, token) in all.iter().enumerate() {
        match token {
            TokenTree::Ident(ident) => {
                let next = all.get(at + 1);
                let name = ident.unraw().to_string();
                if matches!(next, Some(TokenTree::Group(g)) if g.delimiter() == Delimiter::Parenthesis)
                {
                    let previous = at.checked_sub(1).and_then(|i| all.get(i));
                    let kind = if is_punct(previous, '.') {
                        Call::Method
                    } else if is_punct(previous, ':') {
                        Call::Path
                    } else {
                        Call::Bare
                    };
                    body.calls.insert((kind, name.clone()));
                }
                if is_punct(next, '!') {
                    // `m!(..)`: a user macro's body belongs to the caller.
                    if let Some(inner) = macros.get(&name) {
                        body.absorb(inner);
                    }
                    if name == "migrate" {
                        body.migrates = true;
                    }
                }
            }
            TokenTree::Literal(literal) => {
                if let Ok(syn::Lit::Str(s)) = syn::parse_str::<syn::Lit>(&literal.to_string()) {
                    body.strings.insert(s.value());
                }
            }
            TokenTree::Group(group) => tokens_into(group.stream(), macros, body),
            TokenTree::Punct(_) => {}
        }
    }
}

#[derive(Default)]
struct Reader {
    body: Body,
    macros: BTreeMap<String, Body>,
}

impl<'ast> Visit<'ast> for Reader {
    fn visit_expr_call(&mut self, call: &'ast syn::ExprCall) {
        if let syn::Expr::Path(path) = &*call.func
            && let Some(last) = path.path.segments.last()
        {
            let kind = if path.path.segments.len() == 1 {
                Call::Bare
            } else {
                Call::Path
            };
            self.body
                .calls
                .insert((kind, last.ident.unraw().to_string()));
        }
        syn::visit::visit_expr_call(self, call);
    }

    fn visit_expr_method_call(&mut self, call: &'ast syn::ExprMethodCall) {
        let method = call.method.unraw().to_string();
        if matches!(method.as_str(), "run" | "run_direct" | "undo")
            && let syn::Expr::Path(receiver) = &*call.receiver
            && receiver
                .path
                .segments
                .last()
                .is_some_and(|s| s.ident == "MIGRATOR")
        {
            self.body.migrates = true;
        }
        self.body.calls.insert((Call::Method, method));
        syn::visit::visit_expr_method_call(self, call);
    }

    /// `Type::method` passed as a value (`.map(Store::load)`): an edge.
    fn visit_expr_path(&mut self, path: &'ast syn::ExprPath) {
        if path.path.segments.len() > 1
            && let Some(last) = path.path.segments.last()
        {
            self.body
                .calls
                .insert((Call::Path, last.ident.unraw().to_string()));
        }
        syn::visit::visit_expr_path(self, path);
    }

    fn visit_lit_str(&mut self, lit: &'ast syn::LitStr) {
        self.body.strings.insert(lit.value());
    }

    fn visit_macro(&mut self, mac: &'ast syn::Macro) {
        let last = mac
            .path
            .segments
            .last()
            .map(|s| s.ident.unraw().to_string());
        if last.as_deref() == Some("migrate") {
            self.body.migrates = true;
        }
        if let Some(inner) = last.and_then(|name| self.macros.get(&name)) {
            let inner = inner.clone();
            self.body.absorb(&inner);
        }
        let macros = std::mem::take(&mut self.macros);
        tokens_into(mac.tokens.clone(), &macros, &mut self.body);
        self.macros = macros;
    }
}

fn read_body(macros: &BTreeMap<String, Body>, visit: impl FnOnce(&mut Reader)) -> Body {
    let mut reader = Reader {
        macros: macros.clone(),
        ..Reader::default()
    };
    visit(&mut reader);
    reader.body
}

impl Graph {
    pub(super) fn build(sources: &[Source]) -> Self {
        let mut graph = Graph::default();
        // `macro_rules!` first: their bodies are attributed to callers.
        for source in sources {
            collect_macros(&source.file.items, &mut graph.macros);
        }
        let macros = graph.macros.clone();
        for source in sources {
            collect_fns(&source.file.items, source, &macros, &mut graph);
        }
        for (file, name) in graph.fns.keys() {
            graph
                .by_name
                .entry(name.clone())
                .or_default()
                .push((file.clone(), name.clone()));
        }
        graph
    }

    fn add(&mut self, source: &Source, name: String, body: Body, method: bool) {
        let node = self.fns.entry((source.path.clone(), name)).or_default();
        node.body.absorb(&body);
        node.free |= !method;
        node.method |= method;
        node.bin = source.bin;
    }

    /// The sinks: the explicit list plus every discovered migrator runner.
    fn sinks(&self) -> BTreeSet<Key> {
        let mut sinks: BTreeSet<Key> = SINKS
            .iter()
            .map(|(f, n)| ((*f).to_owned(), (*n).to_owned()))
            .collect();
        sinks.extend(
            self.fns
                .iter()
                .filter(|(_, node)| node.body.migrates)
                .map(|(key, _)| key.clone()),
        );
        sinks
    }

    /// The functions a call could reach.
    fn targets(&self, from_bin: bool, kind: Call, name: &str) -> Vec<Key> {
        self.by_name
            .get(name)
            .into_iter()
            .flatten()
            .filter(|key| {
                let node = &self.fns[*key];
                (from_bin || !node.bin)
                    && match kind {
                        Call::Method => node.method,
                        Call::Bare => node.free,
                        Call::Path => node.free || node.method,
                    }
            })
            .cloned()
            .collect()
    }

    /// Functions reachable from `from`, with the caller that led to each.
    fn reach(&self, from: &Key) -> BTreeMap<Key, Option<Key>> {
        let mut seen: BTreeMap<Key, Option<Key>> = BTreeMap::new();
        let mut queue = VecDeque::from([from.clone()]);
        seen.insert(from.clone(), None);
        while let Some(current) = queue.pop_front() {
            let Some(node) = self.fns.get(&current) else {
                continue;
            };
            for (kind, name) in &node.body.calls {
                for target in self.targets(node.bin, *kind, name) {
                    if !seen.contains_key(&target) {
                        seen.insert(target.clone(), Some(current.clone()));
                        queue.push_back(target);
                    }
                }
            }
        }
        seen
    }
}

fn collect_macros(items: &[syn::Item], out: &mut BTreeMap<String, Body>) {
    for item in items {
        match item {
            syn::Item::Macro(m) => {
                if let Some(ident) = &m.ident {
                    let mut body = Body::default();
                    tokens_into(m.mac.tokens.clone(), &BTreeMap::new(), &mut body);
                    out.insert(ident.unraw().to_string(), body);
                }
            }
            syn::Item::Mod(module) => {
                if let Some((_, inner)) = &module.content {
                    collect_macros(inner, out);
                }
            }
            _ => {}
        }
    }
}

fn collect_fns(
    items: &[syn::Item],
    source: &Source,
    macros: &BTreeMap<String, Body>,
    graph: &mut Graph,
) {
    for item in items {
        match item {
            syn::Item::Fn(f) => {
                let body = read_body(macros, |r| r.visit_item_fn(f));
                graph.add(source, f.sig.ident.unraw().to_string(), body, false);
            }
            syn::Item::Impl(imp) => {
                for member in &imp.items {
                    if let syn::ImplItem::Fn(f) = member {
                        let body = read_body(macros, |r| r.visit_impl_item_fn(f));
                        graph.add(source, f.sig.ident.unraw().to_string(), body, true);
                    }
                }
            }
            syn::Item::Trait(tr) => {
                for member in &tr.items {
                    if let syn::TraitItem::Fn(f) = member
                        && f.default.is_some()
                    {
                        let body = read_body(macros, |r| r.visit_trait_item_fn(f));
                        graph.add(source, f.sig.ident.unraw().to_string(), body, true);
                    }
                }
            }
            syn::Item::Mod(module) => {
                if let Some((_, inner)) = &module.content {
                    collect_fns(inner, source, macros, graph);
                }
            }
            _ => {}
        }
    }
}

fn describe(path: &BTreeMap<Key, Option<Key>>, to: &Key) -> String {
    let mut chain = vec![format!("{}::{}", to.0, to.1)];
    let mut at = to;
    while let Some(Some(parent)) = path.get(at) {
        chain.push(format!("{}::{}", parent.0, parent.1));
        at = parent;
    }
    chain.reverse();
    chain.join(" -> ")
}

/// Rule 1 and 4: what `serve` reaches.
pub(super) fn serve_problems(graph: &Graph, entry: &Key) -> Vec<String> {
    let mut out = Vec::new();
    if !graph.fns.contains_key(entry) {
        return vec![format!("entry point {}::{} not found", entry.0, entry.1)];
    }
    let reach = graph.reach(entry);
    for sink in graph.sinks() {
        if reach.contains_key(&sink) {
            out.push(format!(
                "serve reaches {}::{} ({})",
                sink.0,
                sink.1,
                describe(&reach, &sink)
            ));
        }
    }
    for key in reach.keys() {
        let Some(node) = graph.fns.get(key) else {
            continue;
        };
        for name in SUBCOMMANDS {
            if node.body.strings.contains(*name) {
                out.push(format!(
                    "{}::{} holds the string {name:?}, a sink's subcommand name",
                    key.0, key.1
                ));
            }
        }
    }
    out
}

/// Rule 1's guard: every listed sink exists, and discovery finds the runner.
pub(super) fn sink_problems(graph: &Graph) -> Vec<String> {
    let mut out: Vec<String> = SINKS
        .iter()
        .filter(|(f, n)| !graph.fns.contains_key(&((*f).to_owned(), (*n).to_owned())))
        .map(|(f, n)| format!("listed sink {f}::{n} no longer exists: update SINKS"))
        .collect();
    let runner = ("store.rs".to_owned(), "migrate_enterprise".to_owned());
    if !graph.fns.get(&runner).is_some_and(|n| n.body.migrates) {
        out.push("discovery no longer finds the function that runs MIGRATOR".to_owned());
    }
    out
}

fn find_fn<'a>(sources: &'a [Source], file: &str, name: &str) -> Option<&'a syn::ItemFn> {
    sources
        .iter()
        .filter(|s| s.path == file)
        .flat_map(|s| s.file.items.iter())
        .find_map(|item| match item {
            syn::Item::Fn(f) if f.sig.ident == name => Some(f),
            _ => None,
        })
}

fn direct_calls(
    macros: &BTreeMap<String, Body>,
    visit: impl FnOnce(&mut Reader),
) -> BTreeSet<String> {
    read_body(macros, visit).names()
}

/// Rules 2 and 3.
pub(super) fn dispatch_problems(sources: &[Source], graph: &Graph) -> Vec<String> {
    let sinks: BTreeSet<String> = graph.sinks().into_iter().map(|(_, n)| n).collect();
    let macros = &graph.macros;
    let mut out = Vec::new();
    for name in ["main", "run"] {
        let Some(f) = find_fn(sources, "main.rs", name) else {
            out.push(format!("main.rs::{name} not found"));
            continue;
        };
        for call in direct_calls(macros, |r| r.visit_item_fn(f)).intersection(&sinks) {
            out.push(format!(
                "main.rs::{name} calls {call}, which every command (serve too) runs"
            ));
        }
    }
    let Some(dispatch) = find_fn(sources, "commands.rs", "dispatch") else {
        out.push("commands.rs::dispatch not found".to_owned());
        return out;
    };
    // Statements of `dispatch` that are not the final `match`.
    let mut arms: Vec<&syn::Arm> = Vec::new();
    for stmt in &dispatch.block.stmts {
        if let syn::Stmt::Expr(syn::Expr::Match(m), _) = stmt {
            arms.extend(m.arms.iter());
        } else {
            for call in direct_calls(macros, |r| r.visit_stmt(stmt)).intersection(&sinks) {
                out.push(format!(
                    "commands.rs::dispatch calls {call} outside its match"
                ));
            }
        }
    }
    let serve_arms: Vec<&syn::Arm> = arms
        .iter()
        .copied()
        .filter(|arm| {
            let mut idents = Idents::default();
            idents.visit_pat(&arm.pat);
            idents.0.iter().any(|i| i == "Serve") || matches!(arm.pat, syn::Pat::Wild(_))
        })
        .collect();
    if serve_arms.is_empty() {
        out.push("dispatch has no `Command::Serve` arm".to_owned());
    }
    for arm in serve_arms {
        let calls = direct_calls(macros, |r| r.visit_expr(&arm.body));
        if !calls.contains("serve") || calls.intersection(&sinks).next().is_some() {
            out.push(format!(
                "the Serve arm of dispatch must call `serve` and no sink; it calls {calls:?}"
            ));
        }
    }
    out
}

#[derive(Default)]
struct Idents(Vec<String>);

impl<'ast> Visit<'ast> for Idents {
    fn visit_ident(&mut self, ident: &'ast proc_macro2::Ident) {
        self.0.push(ident.unraw().to_string());
    }
}

