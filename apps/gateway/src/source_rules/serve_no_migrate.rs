//! `serve` and the container entrypoint never migrate or bootstrap (AGENTS.md
//! invariant and Deployment rule, #591). The Dockerfiles and the Helm chart
//! are checked by `tests/entrypoint-no-migrate.test.mjs` and
//! `tests/helm-chart.test.mjs`; this module checks the Rust side with one
//! call graph over the whole production build (library and binary):
//!
//! 1. nothing reachable from `serve` (commands/serve.rs) is a *sink*: a
//!    function that applies migrations (`Store::migrate_enterprise`), applies
//!    runtime grants, seeds or provisions (`bootstrap::seed`,
//!    `bootstrap::provision_user`, `demo::seed`, `demo::add_missing_personas`),
//!    or one of the `commands.rs` entry points of those;
//! 2. nothing reachable from `main` or `run` (main.rs), which every command
//!    runs, is a sink. `commands::dispatch` is entered only through the
//!    statements outside its `match` and the `Command::Serve` arm (the wildcard
//!    arm counts as one): the other arms are the explicit commands and are
//!    excluded, nothing else is. So a wrapper called from the Serve arm, or a
//!    migrate inside `Config::connect` or a `Store::with_*` builder, fails;
//! 3. the Serve arm exists and calls `serve`;
//! 4. no string reachable from `serve`, `main` or `run` is a bare subcommand name of a sink
//!    (`"migrate"`, `"--grants"`, a `const` or `concat!` that spells one),
//!    which would be a re-exec.
//!
//! Edges are resolved by name and call shape: a method call `x.run()` (also
//! `x.run::<T>()`) reaches every method called `run`, a bare call `run()` or a
//! single-segment path used as a value (`retry(migrate)`, `.map(boot)`; local
//! bindings of that name excluded) every free function of that name, a path
//! `T::run` (call or value) both; `use a::seed as sow` resolves; library code
//! cannot reach the binary; calls inside macro arguments and `macro_rules!`
//! bodies count, and in macro arguments so do `Type::f` used as a value and
//! `x.f::<T>()`. The graph over-approximates (same-named methods are merged),
//! so a false path is possible; it would be fixed or reasoned about, never
//! ignored.
//!
//! Sinks are the explicit list [`SINKS`] (each must still exist) plus every
//! function found to write the schema: one that calls `.run`/`.run_direct`/
//! `.undo` on a static initialised with `sqlx::migrate!` or `Migrator::new`,
//! calls `Migrator::new` or `Migrator::run`/`run_direct`/`undo` as a path,
//! passes such a static as a call argument (`f(&MIGRATOR)`), invokes `migrate!`, or names `RUNTIME_GRANTS_SQL` or
//! `include_str!`s the grants file.
//!
//! Cannot see: calls through function pointers or closures stored in data and
//! called under another name; a bare function name passed as a value inside
//! macro arguments; a migrator reached through a local variable; code
//! generated by a procedural macro or by an item-position `macro_rules!` that
//! defines functions; ad-hoc `INSERT`s or DDL written inline in a function
//! that is not a listed sink; SQL or a database function that migrates;
//! another process; a re-exec whose subcommand is not a bare string in the
//! tree; implicit trait calls (`.into()` reaching `From::from`, `?`, `Drop`,
//! iterator `next`, `IntoFuture`); a migrator held in a struct field or a
//! local binding (`let m = &MIGRATOR; m.run(..)`). Calls made in dependencies
//! are out of scope.
use std::collections::{BTreeMap, BTreeSet, VecDeque};

use proc_macro2::{Delimiter, TokenStream, TokenTree};
use syn::{ext::IdentExt, visit::Visit};

use super::tree::Source;

/// (file, function): the functions that migrate, grant, seed or provision.
const SINKS: &[(&str, &str)] = &[
    ("store.rs", "migrate_enterprise"),
    ("store.rs", "apply_runtime_grants"),
    ("bootstrap.rs", "seed"),
    ("bootstrap.rs", "provision_user"),
    ("demo.rs", "seed"),
    ("demo.rs", "add_missing_personas"),
    ("commands.rs", "migrate"),
    ("commands.rs", "grants"),
    ("commands.rs", "bootstrap_dev"),
    ("commands.rs", "bootstrap_demo"),
    ("commands.rs", "provision_user"),
];

/// The CLI subcommand names of the sinks.
const SUBCOMMANDS: &[&str] = &[
    "migrate",
    "grants",
    "bootstrap-dev",
    "bootstrap-demo",
    "provision-user",
];

const ENTRY: (&str, &str) = ("commands/serve.rs", "serve");
const SHARED_ENTRIES: &[(&str, &str)] = &[("main.rs", "main"), ("main.rs", "run")];
const DISPATCH: (&str, &str) = ("commands.rs", "dispatch");

type Key = (String, String);

/// How a function is called.
#[derive(Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Debug)]
enum Call {
    /// `f(..)`, or a single-segment path used as a value.
    Bare,
    /// `x.f(..)`
    Method,
    /// `T::f(..)`, `module::f(..)`, or such a path used as a value.
    Path,
}

#[derive(Default, Clone)]
struct Body {
    calls: BTreeSet<(Call, String)>,
    strings: BTreeSet<String>,
    /// Writes the schema or grants (runs a migrator, names the grants file).
    migrates: bool,
}

impl Body {
    fn absorb(&mut self, other: &Body) {
        self.calls.extend(other.calls.iter().cloned());
        self.strings.extend(other.strings.iter().cloned());
        self.migrates |= other.migrates;
    }

    fn names(&self) -> BTreeSet<String> {
        self.calls.iter().map(|(_, n)| n.clone()).collect()
    }
}

#[derive(Default)]
struct Node {
    body: Body,
    free: bool,
    method: bool,
    bin: bool,
}

/// What the whole tree defines that bodies refer to.
#[derive(Default)]
struct Index {
    macros: BTreeMap<String, Body>,
    /// Name of a `const`/`static` initialised with a string literal.
    consts: BTreeMap<String, BTreeSet<String>>,
    /// Names of statics/consts initialised with `migrate!` or `Migrator::new`.
    migrators: BTreeSet<String>,
}

#[derive(Default)]
pub(super) struct Graph {
    /// Every function and method, merged by (file, name).
    fns: BTreeMap<Key, Node>,
    by_name: BTreeMap<String, Vec<Key>>,
    index: Index,
}

fn is_punct(token: Option<&TokenTree>, c: char) -> bool {
    matches!(token, Some(TokenTree::Punct(p)) if p.as_char() == c)
}

fn string_of(literal: &proc_macro2::Literal) -> Option<String> {
    match syn::parse_str::<syn::Lit>(&literal.to_string()) {
        Ok(syn::Lit::Str(s)) => Some(s.value()),
        _ => None,
    }
}

/// The string a `concat!(..)` argument list spells.
fn concat_of(tokens: TokenStream) -> String {
    tokens
        .into_iter()
        .filter_map(|t| match t {
            TokenTree::Literal(l) => string_of(&l).or_else(|| Some(l.to_string())),
            _ => None,
        })
        .collect()
}

fn tokens_into(tokens: TokenStream, index: &Index, body: &mut Body) {
    let all: Vec<TokenTree> = tokens.into_iter().collect();
    for (at, token) in all.iter().enumerate() {
        match token {
            TokenTree::Ident(ident) => {
                let next = all.get(at + 1);
                let name = ident.unraw().to_string();
                let previous = at.checked_sub(1).and_then(|i| all.get(i));
                let after_path = is_punct(previous, ':')
                    && at
                        .checked_sub(2)
                        .and_then(|i| all.get(i))
                        .is_some_and(|t| is_punct(Some(t), ':'));
                let called = matches!(next, Some(TokenTree::Group(g)) if g.delimiter() == Delimiter::Parenthesis);
                // `x.f::<T>()`
                let turbofish = is_punct(previous, '.')
                    && is_punct(next, ':')
                    && is_punct(all.get(at + 2), ':')
                    && is_punct(all.get(at + 3), '<');
                if called || after_path || turbofish {
                    let kind = if is_punct(previous, '.') {
                        Call::Method
                    } else if after_path {
                        Call::Path
                    } else {
                        Call::Bare
                    };
                    body.calls.insert((kind, name.clone()));
                }
                if turbofish {
                    body.calls.insert((Call::Method, name.clone()));
                }
                if name == "RUNTIME_GRANTS_SQL" {
                    body.migrates = true;
                }
                if let Some(values) = index.consts.get(&name) {
                    body.strings.extend(values.iter().cloned());
                }
                if is_punct(next, '!') {
                    // `m!(..)`: a user macro's body belongs to the caller.
                    if let Some(inner) = index.macros.get(&name) {
                        body.absorb(inner);
                    }
                    if name == "migrate" {
                        body.migrates = true;
                    }
                    if name == "concat"
                        && let Some(TokenTree::Group(g)) = all.get(at + 2)
                    {
                        body.strings.insert(concat_of(g.stream()));
                    }
                }
            }
            TokenTree::Literal(literal) => {
                if let Some(value) = string_of(literal) {
                    body.strings.insert(value);
                }
            }
            TokenTree::Group(group) => tokens_into(group.stream(), index, body),
            TokenTree::Punct(_) => {}
        }
    }
}

/// The expression with references, parentheses and dereferences removed.
fn stripped(mut expr: &syn::Expr) -> &syn::Expr {
    loop {
        expr = match expr {
            syn::Expr::Reference(r) => &r.expr,
            syn::Expr::Paren(p) => &p.expr,
            syn::Expr::Group(g) => &g.expr,
            syn::Expr::Unary(u) if matches!(u.op, syn::UnOp::Deref(_)) => &u.expr,
            other => return other,
        };
    }
}

struct Reader<'a> {
    body: Body,
    index: &'a Index,
    /// Names bound by any pattern in the function (parameters, `let`, `match`,
    /// closures): a single-segment path with one of these names is a variable.
    locals: BTreeSet<String>,
    /// Single-segment paths seen, resolved against `locals` at the end.
    singles: BTreeSet<String>,
}

impl<'a> Reader<'a> {
    fn new(index: &'a Index) -> Self {
        Reader {
            body: Body::default(),
            index,
            locals: BTreeSet::new(),
            singles: BTreeSet::new(),
        }
    }

    fn finish(mut self) -> Body {
        for name in &self.singles {
            if !self.locals.contains(name) {
                self.body.calls.insert((Call::Bare, name.clone()));
            }
        }
        self.body
    }
}

impl Reader<'_> {
    /// A migrator static handed to a function (`f(&MIGRATOR)`) can be run there.
    /// Receivers (`MIGRATOR.iter()`) are not arguments.
    fn migrator_arguments<'e>(&mut self, args: impl Iterator<Item = &'e syn::Expr>) {
        for arg in args {
            if let syn::Expr::Path(path) = stripped(arg)
                && path
                    .path
                    .segments
                    .last()
                    .is_some_and(|s| self.index.migrators.contains(&s.ident.unraw().to_string()))
            {
                self.body.migrates = true;
            }
        }
    }
}

impl<'ast> Visit<'ast> for Reader<'_> {
    fn visit_pat_ident(&mut self, pat: &'ast syn::PatIdent) {
        self.locals.insert(pat.ident.unraw().to_string());
        syn::visit::visit_pat_ident(self, pat);
    }

    fn visit_expr_call(&mut self, call: &'ast syn::ExprCall) {
        if let syn::Expr::Path(path) = &*call.func {
            let segments: Vec<String> = path
                .path
                .segments
                .iter()
                .map(|s| s.ident.unraw().to_string())
                .collect();
            if segments.len() >= 2
                && segments[segments.len() - 2] == "Migrator"
                && matches!(
                    segments[segments.len() - 1].as_str(),
                    "new" | "run" | "run_direct" | "undo"
                )
            {
                self.body.migrates = true;
            }
            self.migrator_arguments(call.args.iter());
            if let Some(last) = segments.last() {
                let kind = if segments.len() == 1 {
                    Call::Bare
                } else {
                    Call::Path
                };
                self.body.calls.insert((kind, last.clone()));
            }
        }
        syn::visit::visit_expr_call(self, call);
    }

    fn visit_expr_method_call(&mut self, call: &'ast syn::ExprMethodCall) {
        let method = call.method.unraw().to_string();
        if matches!(method.as_str(), "run" | "run_direct" | "undo")
            && let syn::Expr::Path(receiver) = stripped(&call.receiver)
            && receiver
                .path
                .segments
                .last()
                .is_some_and(|s| self.index.migrators.contains(&s.ident.unraw().to_string()))
        {
            self.body.migrates = true;
        }
        self.body.calls.insert((Call::Method, method));
        self.migrator_arguments(call.args.iter());
        syn::visit::visit_expr_method_call(self, call);
    }

    /// A path used as a value (`.map(Store::load)`, `retry(migrate)`): an edge.
    fn visit_expr_path(&mut self, path: &'ast syn::ExprPath) {
        let segments: Vec<String> = path
            .path
            .segments
            .iter()
            .map(|s| s.ident.unraw().to_string())
            .collect();
        if let Some(last) = segments.last() {
            if last == "RUNTIME_GRANTS_SQL" {
                self.body.migrates = true;
            }
            if let Some(values) = self.index.consts.get(last) {
                self.body.strings.extend(values.iter().cloned());
            }
            if segments.len() > 1 {
                self.body.calls.insert((Call::Path, last.clone()));
            } else {
                self.singles.insert(last.clone());
            }
        }
        syn::visit::visit_expr_path(self, path);
    }

    fn visit_lit_str(&mut self, lit: &'ast syn::LitStr) {
        self.body.strings.insert(lit.value());
    }

    fn visit_macro(&mut self, mac: &'ast syn::Macro) {
        let last = mac
            .path
            .segments
            .last()
            .map(|s| s.ident.unraw().to_string());
        if last.as_deref() == Some("migrate") {
            self.body.migrates = true;
        }
        if last.as_deref() == Some("concat") {
            self.body.strings.insert(concat_of(mac.tokens.clone()));
        }
        if last.as_deref() == Some("include_str")
            && mac
                .tokens
                .clone()
                .into_iter()
                .any(|t| matches!(&t, TokenTree::Literal(l) if string_of(l).is_some_and(|s| s.contains("runtime-grants.sql"))))
        {
            self.body.migrates = true;
        }
        if let Some(inner) = last.and_then(|name| self.index.macros.get(&name)) {
            self.body.absorb(inner);
        }
        tokens_into(mac.tokens.clone(), self.index, &mut self.body);
    }
}

fn read_body(index: &Index, visit: impl FnOnce(&mut Reader)) -> Body {
    let mut reader = Reader::new(index);
    visit(&mut reader);
    reader.finish()
}

/// `use a::seed as sow;` anywhere in a file: alias -> original name.
#[derive(Default)]
struct Aliases(BTreeMap<String, String>);

impl<'ast> Visit<'ast> for Aliases {
    fn visit_use_rename(&mut self, rename: &'ast syn::UseRename) {
        let alias = rename.rename.unraw().to_string();
        if alias != "_" {
            self.0.insert(alias, rename.ident.unraw().to_string());
        }
    }
}

impl Graph {
    pub(super) fn build(sources: &[Source]) -> Self {
        let mut graph = Graph::default();
        // `macro_rules!`, constants and migrators first: bodies refer to them.
        for source in sources {
            collect_macros(&source.file.items, &mut graph.index.macros);
        }
        for source in sources {
            collect_values(&source.file.items, &mut graph.index);
        }
        let index = std::mem::take(&mut graph.index);
        for source in sources {
            let mut aliases = Aliases::default();
            aliases.visit_file(&source.file);
            collect_fns(&source.file.items, source, &index, &aliases.0, &mut graph);
        }
        graph.index = index;
        for (file, name) in graph.fns.keys() {
            graph
                .by_name
                .entry(name.clone())
                .or_default()
                .push((file.clone(), name.clone()));
        }
        graph
    }

    fn add(
        &mut self,
        source: &Source,
        name: String,
        mut body: Body,
        method: bool,
        aliases: &BTreeMap<String, String>,
    ) {
        let renamed: Vec<(Call, String)> = body
            .calls
            .iter()
            .filter_map(|(kind, n)| aliases.get(n).map(|orig| (*kind, orig.clone())))
            .collect();
        body.calls.extend(renamed);
        let node = self.fns.entry((source.path.clone(), name)).or_default();
        node.body.absorb(&body);
        node.free |= !method;
        node.method |= method;
        node.bin = source.bin;
    }

    /// The sinks: the explicit list plus every discovered schema writer.
    fn sinks(&self) -> BTreeSet<Key> {
        let mut sinks: BTreeSet<Key> = SINKS
            .iter()
            .map(|(f, n)| ((*f).to_owned(), (*n).to_owned()))
            .collect();
        sinks.extend(
            self.fns
                .iter()
                .filter(|(_, node)| node.body.migrates)
                .map(|(key, _)| key.clone()),
        );
        sinks
    }

    /// The functions a call could reach.
    fn targets(&self, from_bin: bool, kind: Call, name: &str) -> Vec<Key> {
        self.by_name
            .get(name)
            .into_iter()
            .flatten()
            .filter(|key| {
                let node = &self.fns[*key];
                (from_bin || !node.bin)
                    && match kind {
                        Call::Method => node.method,
                        Call::Bare => node.free,
                        Call::Path => node.free || node.method,
                    }
            })
            .cloned()
            .collect()
    }

    /// Functions reachable from `from`, with the caller that led to each.
    fn reach(&self, from: &Key) -> BTreeMap<Key, Option<Key>> {
        let mut seen: BTreeMap<Key, Option<Key>> = BTreeMap::new();
        let mut queue = VecDeque::from([from.clone()]);
        seen.insert(from.clone(), None);
        while let Some(current) = queue.pop_front() {
            let Some(node) = self.fns.get(&current) else {
                continue;
            };
            for (kind, name) in &node.body.calls {
                for target in self.targets(node.bin, *kind, name) {
                    if !seen.contains_key(&target) {
                        seen.insert(target.clone(), Some(current.clone()));
                        queue.push_back(target);
                    }
                }
            }
        }
        seen
    }
}

fn collect_macros(items: &[syn::Item], out: &mut BTreeMap<String, Body>) {
    for item in items {
        match item {
            syn::Item::Macro(m) => {
                if let Some(ident) = &m.ident {
                    let mut body = Body::default();
                    tokens_into(m.mac.tokens.clone(), &Index::default(), &mut body);
                    out.insert(ident.unraw().to_string(), body);
                }
            }
            syn::Item::Mod(module) => {
                if let Some((_, inner)) = &module.content {
                    collect_macros(inner, out);
                }
            }
            _ => {}
        }
    }
}

/// Does the expression run `migrate!` or `Migrator::new`?
struct MigratorInit(bool);

impl<'ast> Visit<'ast> for MigratorInit {
    fn visit_macro(&mut self, mac: &'ast syn::Macro) {
        self.0 |= mac
            .path
            .segments
            .last()
            .is_some_and(|s| s.ident == "migrate");
    }
    fn visit_expr_call(&mut self, call: &'ast syn::ExprCall) {
        if let syn::Expr::Path(p) = &*call.func {
            let segments: Vec<_> = p
                .path
                .segments
                .iter()
                .map(|s| s.ident.to_string())
                .collect();
            self.0 |= segments.ends_with(&["Migrator".to_owned(), "new".to_owned()]);
        }
        syn::visit::visit_expr_call(self, call);
    }
}

fn record_value(name: String, expr: &syn::Expr, index: &mut Index) {
    if let syn::Expr::Lit(syn::ExprLit {
        lit: syn::Lit::Str(s),
        ..
    }) = stripped(expr)
    {
        index
            .consts
            .entry(name.clone())
            .or_default()
            .insert(s.value());
    }
    let mut init = MigratorInit(false);
    init.visit_expr(expr);
    if init.0 {
        index.migrators.insert(name);
    }
}

/// String constants and migrator statics, anywhere in the items.
fn collect_values(items: &[syn::Item], index: &mut Index) {
    for item in items {
        match item {
            syn::Item::Const(c) => record_value(c.ident.unraw().to_string(), &c.expr, index),
            syn::Item::Static(s) => record_value(s.ident.unraw().to_string(), &s.expr, index),
            syn::Item::Impl(imp) => {
                for member in &imp.items {
                    if let syn::ImplItem::Const(c) = member {
                        record_value(c.ident.unraw().to_string(), &c.expr, index);
                    }
                }
            }
            syn::Item::Mod(module) => {
                if let Some((_, inner)) = &module.content {
                    collect_values(inner, index);
                }
            }
            _ => {}
        }
    }
}

fn collect_fns(
    items: &[syn::Item],
    source: &Source,
    index: &Index,
    aliases: &BTreeMap<String, String>,
    graph: &mut Graph,
) {
    for item in items {
        match item {
            syn::Item::Fn(f) => {
                let name = f.sig.ident.unraw().to_string();
                let body = if source.path == DISPATCH.0 && name == DISPATCH.1 {
                    serve_view(f, index)
                } else {
                    read_body(index, |r| r.visit_item_fn(f))
                };
                graph.add(source, name, body, false, aliases);
            }
            syn::Item::Impl(imp) => {
                for member in &imp.items {
                    if let syn::ImplItem::Fn(f) = member {
                        let body = read_body(index, |r| r.visit_impl_item_fn(f));
                        graph.add(source, f.sig.ident.unraw().to_string(), body, true, aliases);
                    }
                }
            }
            syn::Item::Trait(tr) => {
                for member in &tr.items {
                    if let syn::TraitItem::Fn(f) = member
                        && f.default.is_some()
                    {
                        let body = read_body(index, |r| r.visit_trait_item_fn(f));
                        graph.add(source, f.sig.ident.unraw().to_string(), body, true, aliases);
                    }
                }
            }
            syn::Item::Mod(module) => {
                if let Some((_, inner)) = &module.content {
                    collect_fns(inner, source, index, aliases, graph);
                }
            }
            _ => {}
        }
    }
}

/// The part of `dispatch` that `serve` runs: its statements outside the
/// final `match` and the `Command::Serve` arm (the wildcard arm counts as one).
/// The other arms are separate commands.
fn serve_view(dispatch: &syn::ItemFn, index: &Index) -> Body {
    let (outside, arms) = split_dispatch(dispatch);
    let mut body = Body::default();
    for stmt in outside {
        body.absorb(&read_body(index, |r| r.visit_stmt(stmt)));
    }
    for arm in serve_arms(&arms) {
        body.absorb(&read_body(index, |r| r.visit_expr(&arm.body)));
    }
    body
}

fn split_dispatch(dispatch: &syn::ItemFn) -> (Vec<&syn::Stmt>, Vec<&syn::Arm>) {
    // The command parameter: the first named parameter.
    let parameter = dispatch.sig.inputs.iter().find_map(|arg| match arg {
        syn::FnArg::Typed(typed) => match &*typed.pat {
            syn::Pat::Ident(ident) => Some(ident.ident.unraw().to_string()),
            _ => None,
        },
        syn::FnArg::Receiver(_) => None,
    });
    let mut outside = Vec::new();
    let mut arms = Vec::new();
    for stmt in &dispatch.block.stmts {
        match stmt {
            syn::Stmt::Expr(syn::Expr::Match(m), _)
                if is_command_match(m, parameter.as_deref()) =>
            {
                arms.extend(m.arms.iter());
            }
            other => outside.push(other),
        }
    }
    (outside, arms)
}

/// The match on the command: its scrutinee is the command parameter, or an
/// arm pattern names a `Command` path. Any other `match` is ordinary code.
fn is_command_match(m: &syn::ExprMatch, parameter: Option<&str>) -> bool {
    if let syn::Expr::Path(path) = stripped(&m.expr)
        && let Some(ident) = path.path.get_ident()
        && Some(ident.unraw().to_string().as_str()) == parameter
    {
        return true;
    }
    m.arms.iter().any(|arm| {
        let mut idents = Idents::default();
        idents.visit_pat(&arm.pat);
        idents.0.iter().any(|i| i == "Command")
    })
}

#[derive(Default)]
struct Idents(Vec<String>);

impl<'ast> Visit<'ast> for Idents {
    fn visit_ident(&mut self, ident: &'ast proc_macro2::Ident) {
        self.0.push(ident.unraw().to_string());
    }
}

fn serve_arms<'a>(arms: &[&'a syn::Arm]) -> Vec<&'a syn::Arm> {
    arms.iter()
        .copied()
        .filter(|arm| {
            let mut idents = Idents::default();
            idents.visit_pat(&arm.pat);
            idents.0.iter().any(|i| i == "Serve") || matches!(arm.pat, syn::Pat::Wild(_))
        })
        .collect()
}

fn describe(path: &BTreeMap<Key, Option<Key>>, to: &Key) -> String {
    let mut chain = vec![format!("{}::{}", to.0, to.1)];
    let mut at = to;
    while let Some(Some(parent)) = path.get(at) {
        chain.push(format!("{}::{}", parent.0, parent.1));
        at = parent;
    }
    chain.reverse();
    chain.join(" -> ")
}

/// The sinks reachable from `entry`.
fn sinks_from(graph: &Graph, entry: &Key, what: &str) -> Vec<String> {
    if !graph.fns.contains_key(entry) {
        return vec![format!("entry point {}::{} not found", entry.0, entry.1)];
    }
    let reach = graph.reach(entry);
    graph
        .sinks()
        .into_iter()
        .filter(|sink| reach.contains_key(sink))
        .map(|sink| {
            format!(
                "{what} reaches {}::{} ({})",
                sink.0,
                sink.1,
                describe(&reach, &sink)
            )
        })
        .collect()
}

/// Rule 4: no string reachable from `entry` is a sink's subcommand name.
fn string_problems(graph: &Graph, entry: &Key) -> Vec<String> {
    let mut out = Vec::new();
    for key in graph.reach(entry).keys() {
        let Some(node) = graph.fns.get(key) else {
            continue;
        };
        for name in SUBCOMMANDS {
            if node
                .body
                .strings
                .iter()
                .any(|s| s.trim_start_matches('-') == *name)
            {
                out.push(format!(
                    "{}::{} holds the string {name:?}, a sink's subcommand name",
                    key.0, key.1
                ));
            }
        }
    }
    out
}

/// Rules 1 and 4: what `serve` reaches.
pub(super) fn serve_problems(graph: &Graph, entry: &Key) -> Vec<String> {
    let mut out = sinks_from(graph, entry, "serve");
    if graph.fns.contains_key(entry) {
        out.extend(string_problems(graph, entry));
    }
    out
}

/// Every listed sink exists, and discovery finds the schema writers.
pub(super) fn sink_problems(graph: &Graph) -> Vec<String> {
    let mut out: Vec<String> = SINKS
        .iter()
        .filter(|(f, n)| !graph.fns.contains_key(&((*f).to_owned(), (*n).to_owned())))
        .map(|(f, n)| format!("listed sink {f}::{n} no longer exists: update SINKS"))
        .collect();
    for (file, name, what) in [
        ("store.rs", "migrate_enterprise", "runs MIGRATOR"),
        (
            "store.rs",
            "apply_runtime_grants",
            "names RUNTIME_GRANTS_SQL",
        ),
    ] {
        let key = (file.to_owned(), name.to_owned());
        if !graph.fns.get(&key).is_some_and(|n| n.body.migrates) {
            out.push(format!(
                "discovery no longer finds the function that {what}"
            ));
        }
    }
    out
}

fn find_fn<'a>(sources: &'a [Source], file: &str, name: &str) -> Option<&'a syn::ItemFn> {
    sources
        .iter()
        .filter(|s| s.path == file)
        .flat_map(|s| s.file.items.iter())
        .find_map(|item| match item {
            syn::Item::Fn(f) if f.sig.ident == name => Some(f),
            _ => None,
        })
}

/// Rules 2 and 3.
pub(super) fn startup_problems(sources: &[Source], graph: &Graph) -> Vec<String> {
    let mut out = Vec::new();
    for (file, name) in SHARED_ENTRIES {
        let key = ((*file).to_owned(), (*name).to_owned());
        if find_fn(sources, file, name).is_none() {
            out.push(format!("{file}::{name} not found"));
            continue;
        }
        out.extend(sinks_from(
            graph,
            &key,
            &format!("{file}::{name} (runs before every command, serve included)"),
        ));
        out.extend(string_problems(graph, &key));
    }
    let Some(dispatch) = find_fn(sources, DISPATCH.0, DISPATCH.1) else {
        out.push(format!("{}::{} not found", DISPATCH.0, DISPATCH.1));
        return out;
    };
    let (_, arms) = split_dispatch(dispatch);
    let serve = serve_arms(&arms);
    if serve.is_empty() {
        out.push("dispatch has no `Command::Serve` arm".to_owned());
    }
    let index = &graph.index;
    for arm in serve {
        let calls = read_body(index, |r| r.visit_expr(&arm.body)).names();
        if !calls.contains("serve") {
            out.push(format!(
                "the Serve arm of dispatch must call `serve`; it calls {calls:?}"
            ));
        }
    }
    // `main` reaches `run`: the same finding is reported once.
    let mut seen = BTreeSet::new();
    out.retain(|problem| seen.insert(problem.clone()));
    out
}

