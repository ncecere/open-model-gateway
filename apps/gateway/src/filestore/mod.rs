//! Encrypted object storage for gateway-owned files (docs/file-storage.md).
//!
//! Every backend stores ciphertext only: [`crypto`] wraps each object in
//! streaming, chunked AES-256-GCM before a backend sees a byte, and verifies
//! every chunk (plus truncation and reordering) on the way out. Backends:
//!
//! - `local`: one directory on the gateway host (0700 directories, 0600 files,
//!   temp file + fsync + atomic rename, no symlink following).
//! - `s3`: S3 and S3-compatible stores (AWS S3, MinIO, RustFS, Cloudflare R2,
//!   Wasabi, Ceph RGW, GCS interoperability) through `aws-sdk-s3`.
//! - memory: tests only ([`memory_store`]).
//!
//! Object keys are generated by the gateway (`<purpose>/<workspace-id|installation>/<uuid>`)
//! and never derived from client input. Metadata (owner, purpose, size, sha256,
//! retention) lives in PostgreSQL (`stored_files`, migration 0019) and is managed by
//! [`files::FileStorage`]; the raw [`FileStore`] trait does not touch the database.
