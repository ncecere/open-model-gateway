/// A stream of plaintext (from [`FileStore::get`]) or caller-provided bytes (to [`FileStore::put`]).
pub type ByteStream = futures::stream::BoxStream<'static, Result<Bytes, FileStoreError>>;

/// Encrypted object storage. Implementations encrypt on `put` and authenticate
/// on `get`; a backend never receives plaintext.
#[async_trait::async_trait]
pub trait FileStore: Send + Sync {
    /// Streams `body` into the store under `key`. Returns the plaintext size
    /// and SHA-256. On any error nothing is left behind (temp files removed,
    /// multipart uploads aborted). A body error is returned unchanged.
    async fn put(
        &self,
        key: &ObjectKey,
        body: ByteStream,
        meta: PutMeta,
    ) -> Result<StoredObject, FileStoreError>;
    /// Decrypted plaintext stream. Every 64 KiB chunk is authenticated before it
    /// is yielded; truncation, reordering or tampering ends the stream with
    /// [`FileStoreError::Integrity`]. Treat any error item as failure of the whole object.
    async fn get(&self, key: &ObjectKey) -> Result<ByteStream, FileStoreError>;
    /// Idempotent: deleting a missing object succeeds.
    async fn delete(&self, key: &ObjectKey) -> Result<(), FileStoreError>;
    /// Size information without reading the object; `None` when absent.
    async fn head(&self, key: &ObjectKey) -> Result<Option<ObjectInfo>, FileStoreError>;
    /// Put/get/delete probe of a small random object under the configured prefix.
    async fn health(&self) -> Result<StoreHealth, FileStoreError>;
}

/// Options for one [`FileStore::put`].
#[derive(Clone, Copy, Debug, Default)]
pub struct PutMeta {
    /// Reject the upload with [`FileStoreError::TooLarge`] once the plaintext exceeds this.
    pub max_bytes: Option<u64>,
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct StoredObject {
    pub key: ObjectKey,
    /// Plaintext bytes.
    pub size: u64,
    /// SHA-256 of the plaintext.
    pub sha256: [u8; 32],
    /// Master key id that wrapped this object's data key.
    pub key_id: String,
    /// Ciphertext bytes held by the backend (header + per-chunk tags).
    pub stored_size: u64,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct ObjectInfo {
    /// Plaintext bytes, derived from the ciphertext length.
    pub size: u64,
    pub stored_size: u64,
}

#[derive(Clone, Debug)]
pub struct StoreHealth {
    pub backend: BackendKind,
    /// Active encryption key id.
    pub key_id: String,
    pub round_trip: Duration,
}

/// Safe, fixed error categories. Never carries paths, keys, bucket names,
/// upstream messages or content.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum FileStoreError {
    NotFound,
    TooLarge,
    /// Authentication failed: tampered, truncated, reordered or malformed ciphertext.
    Integrity,
    /// The object was encrypted under a key id that is not configured.
    KeyUnavailable,
    InvalidKey,
    /// The caller's body stream failed.
    Source,
    Unavailable,
    Timeout,
    /// The backend refused the credentials or permission.
    Denied,
    /// Local backend: a symlink or path outside the store directory.
    UnsafePath,
    /// No file store is configured, or the purpose is turned off.
    Disabled,
}

impl FileStoreError {
    /// Stable snake_case code for metrics, the database and API responses.
    pub fn code(self) -> &'static str {
        match self {
            Self::NotFound => "not_found",
            Self::TooLarge => "too_large",
            Self::Integrity => "integrity",
            Self::KeyUnavailable => "key_unavailable",
            Self::InvalidKey => "invalid_key",
            Self::Source => "source",
            Self::Unavailable => "unavailable",
            Self::Timeout => "timeout",
            Self::Denied => "denied",
            Self::UnsafePath => "unsafe_path",
            Self::Disabled => "disabled",
        }
    }
}

impl fmt::Display for FileStoreError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(match self {
            Self::NotFound => "stored object not found",
            Self::TooLarge => "stored object too large",
            Self::Integrity => "stored object failed integrity verification",
            Self::KeyUnavailable => "stored object encryption key is not configured",
            Self::InvalidKey => "invalid object key",
            Self::Source => "upload source failed",
            Self::Unavailable => "file store unavailable",
            Self::Timeout => "file store timed out",
            Self::Denied => "file store denied access",
            Self::UnsafePath => "unsafe file store path",
            Self::Disabled => "file storage is not enabled",
        })
    }
}

