#!/usr/bin/env bash
# The test run inside the Spark test pod (deploy/spark/test-job.yaml, started by
# scripts/spark-test.py). Environment: OMG_SUITE (lib|integration|web|checks|all), OMG_SHA (the
# exact commit), OMG_REPO_URL (the public repository), OMG_JOBS (build jobs), OMG_TEST_ARGS
# (extra libtest or vitest arguments, lib and web only), OMG_DB_HOST, PGPASSWORD (the run's
# PostgreSQL superuser password; it is never printed: all output passes the redaction below),
# OMG_TARGET_LIMIT_GIB, OMG_TEST_THREADS (libtest threads).
#
# The commands are the ones .github/workflows/ci.yml runs; the lines starting `::omg-test::`
# are the machine-readable progress the tool turns into the summary. Exit status: 0 only if
# every step of every selected suite passed.
set -uo pipefail

SRC=/cache/src
mark() { printf '::omg-test:: %s\n' "$*"; }

# Everything printed passes this filter. The password is generated by the tool (hex), and a
# PostgreSQL URL with a password is redacted whatever the password is.
redact() {
  sed -u -E -e "s/${PGPASSWORD:-__none__}/[redacted]/g" -e 's#(postgres(ql)?://[^:/@[:space:]]+:)[^@[:space:]]+@#\1[redacted]@#g'
}

step() { # step <suite> <name> <command...>: run in the source tree, record the exit status and time
  local suite=$1 name=$2 start=$SECONDS code
  shift 2
  mark "step-start suite=$suite name=$name"
  echo "$suite/$name" >/tmp/omg-step
  ( cd "$SRC" && "$@" )
  code=$?
  mark "step-end suite=$suite name=$name exit=$code seconds=$((SECONDS - start))"
  return "$code"
}

with_db() { # run a command with DATABASE_URL pointing at the run's PostgreSQL
  DATABASE_URL="postgres://postgres:${PGPASSWORD}@${OMG_DB_HOST}:5432/gateway" "$@"
}

with_loopback_db() { # the load-generator tests refuse any host but loopback (CI's service container is on localhost): relay 127.0.0.1:5432 to the service
  local code
  PG_FORWARD_TARGET="$OMG_DB_HOST" node /scripts/pg-forward.mjs &
  local relay=$!
  sleep 1
  DATABASE_URL="postgres://postgres:${PGPASSWORD}@127.0.0.1:5432/gateway" "$@"
  code=$?
  kill "$relay" 2>/dev/null
  wait "$relay" 2>/dev/null
  return "$code"
}

setup_environment() {
  mkdir -p /cache/home /cache/cargo /cache/rustup /cache/target /cache/npm "$SRC"
  export HOME=/cache/home CARGO_HOME=/cache/cargo RUSTUP_HOME=/cache/rustup CARGO_TARGET_DIR=/cache/target
  export NPM_CONFIG_CACHE=/cache/npm
  export PATH="/opt/node/bin:/usr/local/cargo/bin:$PATH"
  # No debug info (smaller cache, less memory). Not incremental, as CI (the one compile OOM-killed at the 10 GiB limit was an incremental one; a changed gateway crate rebuilds in about 2.5 minutes without it).
  export CARGO_INCREMENTAL=0 CARGO_PROFILE_DEV_DEBUG=0 CARGO_PROFILE_TEST_DEBUG=0
  export RUST_TEST_THREADS="$OMG_TEST_THREADS" CARGO_BUILD_JOBS="$OMG_JOBS" CARGO_TERM_COLOR=never CARGO_TERM_PROGRESS_WHEN=never CARGO_NET_RETRY=5
  export CI=true GIT_TERMINAL_PROMPT=0
  mark "environment arch=$(uname -m) cpus=$(awk '{print $1}' /sys/fs/cgroup/cpu.max 2>/dev/null)/$(awk '{print $2}' /sys/fs/cgroup/cpu.max 2>/dev/null) jobs=$OMG_JOBS test_threads=$OMG_TEST_THREADS"
  if [ ! -e /cache/rustup/.seeded ]; then
    # The image's toolchain is the starting point; rustup adds only what rust-toolchain.toml names.
    cp -a /usr/local/rustup/. /cache/rustup/ && touch /cache/rustup/.seeded || return 1
  fi
  node --version && npm --version || return 1
}

prepare_source() {
  mkdir -p "$SRC" && cd "$SRC" || return 1
  [ -d .git ] || git init -q . || return 1
  # An exact commit of the public repository, no credentials. A commit that was never pushed cannot be fetched.
  if ! git fetch -q --no-tags --depth 1 "$OMG_REPO_URL" "$OMG_SHA"; then
    echo "cannot fetch $OMG_SHA from $OMG_REPO_URL: push the branch first"
    return 1
  fi
  # `checkout -f` of the commit that is already checked out still rewrites every file, and Cargo then
  # recompiles the whole workspace crate (measured: 2 minutes); a different commit rewrites only what differs.
  if [ "$(git rev-parse -q --verify HEAD 2>/dev/null)" != "$OMG_SHA" ] || [ -n "$(git status --porcelain --untracked-files=no)" ]; then
    git checkout -q -f --detach FETCH_HEAD || return 1
  fi
  git clean -q -ffdx || return 1
  if [ "$(git rev-parse HEAD)" != "$OMG_SHA" ]; then
    echo "HEAD is $(git rev-parse HEAD), not $OMG_SHA"
    return 1
  fi
  mark "source commit=$OMG_SHA"
}

prepare_toolchain() {
  local channel
  channel=$(sed -n 's/^channel *= *"\([^"]*\)".*/\1/p' rust-toolchain.toml)
  [ -n "$channel" ] || { echo "rust-toolchain.toml names no channel"; return 1; }
  # Idempotent: nothing is downloaded when the cache already has the toolchain and components.
  rustup toolchain install "$channel" --profile minimal --component rustfmt --component clippy --no-self-update || return 1
  rustc --version && cargo --version
}

trim_target() { # keep the cache within OMG_TARGET_LIMIT_GIB: drop incremental data, then everything
  local used limit=$((OMG_TARGET_LIMIT_GIB * 1024 * 1024))
  used=$(du -sk /cache/target | awk '{print $1}')
  if [ "$used" -gt "$limit" ]; then
    echo "target directory is $((used / 1024 / 1024)) GiB (limit $OMG_TARGET_LIMIT_GIB): removing incremental data"
    find /cache/target -maxdepth 2 -name incremental -type d -prune -exec rm -rf {} +
    used=$(du -sk /cache/target | awk '{print $1}')
    if [ "$used" -gt "$limit" ]; then
      echo "still $((used / 1024 / 1024)) GiB: removing the target directory"
      find /cache/target -mindepth 1 -maxdepth 1 -exec rm -rf {} +
    fi
  fi
  mark "cache target_mib=$(($(du -sk /cache/target | awk '{print $1}') / 1024))"
}

NPM_READY=
prepare_npm() {
  [ "$NPM_READY" = ok ] && return 0
  step "$1" npm-ci npm ci || return 1
  NPM_READY=ok
}

wait_db() {
  local i
  for i in $(seq 1 120); do
    if (exec 3<>"/dev/tcp/$OMG_DB_HOST/5432") 2>/dev/null; then
      mark "database host=$OMG_DB_HOST ready"
      return 0
    fi
    sleep 5
  done
  echo "the PostgreSQL service $OMG_DB_HOST did not accept connections within 10 minutes"
  return 1
}

extra_args() { read -r -a EXTRA <<<"$OMG_TEST_ARGS"; }

suite_checks() {
  local bad=0
  step checks fmt cargo fmt --all -- --check || bad=1
  step checks clippy-workspace cargo clippy --workspace --all-targets --all-features -- -D warnings || bad=1
  step checks clippy-shipped cargo clippy -p open-model-gateway --bins --lib --locked -- -D warnings || bad=1
  return "$bad"
}

# The gateway library is one test binary of about 2,450 tests. In one process its memory grows to more
# than 10 GiB (measured on the Spark: OOM-killed at the 10 GiB limit after 1,789 tests), so, as CI does
# (.github/scripts/rust-shards.mjs: exact names, round-robin), it runs as OMG_LIB_SHARDS processes one
# after the other. A test filter (OMG_TEST_ARGS) runs unsharded: it selects few tests.
OMG_LIB_SHARDS=${OMG_LIB_SHARDS:-4}
LIB=(cargo test -p open-model-gateway --all-features --lib)

lib_shard() { # lib_shard <index> <names file>: the tests of one shard, and a check that every one was accounted for
  local index=$1 names=$2 expected out code
  expected=$(awk -v k="$index" -v n="$OMG_LIB_SHARDS" 'NR % n == k' "$names" | wc -l)
  out=$(mktemp /tmp/lib-shard.XXXXXX)
  mark "lib-shard index=$index tests=$expected"
  with_db "${LIB[@]}" -- --exact $(awk -v k="$index" -v n="$OMG_LIB_SHARDS" 'NR % n == k' "$names") 2>&1 | tee "$out"
  code=${PIPESTATUS[0]}
  if ! awk -v want="$expected" '/^test result: / { for (i = 1; i <= NF; i++) { if ($i == "passed;" || $i == "failed;" || $i == "ignored;") n += $(i - 1) } found = 1 } END { exit !(found && n == want) }' "$out"; then
    echo "shard $index: the passed, failed and ignored counts are not the $expected tests selected"
    code=1
  fi
  rm -f "$out"
  return "$code"
}

suite_lib() {
  local bad=0 names index
  prepare_npm lib || return 1
  step lib build "${LIB[@]}" --no-run || return 1
  wait_db || return 1
  extra_args
  if [ -n "$OMG_TEST_ARGS" ]; then
    step lib filtered with_db "${LIB[@]}" -- "${EXTRA[@]}"
    return
  fi
  names=$(mktemp /tmp/lib-names.XXXXXX)
  ( cd "$SRC" && "${LIB[@]}" -- --list --format terse 2>/dev/null ) | sed -n 's/: test$//p' | sort >"$names"
  mark "lib-inventory tests=$(wc -l <"$names")"
  [ -s "$names" ] || { echo "no lib tests listed"; return 1; }
  for ((index = 0; index < OMG_LIB_SHARDS; index++)); do
    step lib "shard-$index" lib_shard "$index" "$names" || bad=1
  done
  rm -f "$names"
  return "$bad"
}

integration_test_args() { # one `--test <name>` per gateway test target, minus the two other steps below
  cargo metadata --no-deps --all-features --format-version 1 --locked | node -e '
    const meta = JSON.parse(require("fs").readFileSync(0, "utf8"));
    const own = new Set(["filestore_s3", "runtime_privileges"]);
    const names = [];
    for (const pkg of meta.packages) {
      if (pkg.name !== "open-model-gateway") continue;
      for (const t of pkg.targets) if (t.kind.length === 1 && t.kind[0] === "test" && t.test && !own.has(t.name)) names.push(t.name);
    }
    console.log(names.sort().map(n => `--test ${n}`).join("\n"));
  '
}

suite_integration() {
  local bad=0 selected
  prepare_npm integration || return 1
  wait_db || return 1
  selected=$(cd "$SRC" && integration_test_args) || { echo "cannot list the gateway test targets"; return 1; }
  # Every gateway test target, the gateway binary's own tests, then the targets CI gives to gateway-special
  # except filestore_s3 (it starts MinIO and RustFS containers: no Docker in a pod) and the backup drill.
  # shellcheck disable=SC2086
  step integration targets with_db cargo test -p open-model-gateway --all-features --no-fail-fast $selected --bins || bad=1
  step integration runtime-privileges with_db cargo test -p open-model-gateway --all-features --test runtime_privileges || bad=1
  step integration runtime-privileges-ignored with_db cargo test -p open-model-gateway --all-features --test runtime_privileges -- --ignored --test-threads=1 || bad=1
  step integration key-issuance-contention with_db env RUST_TEST_NOCAPTURE=1 cargo test -p open-model-gateway --all-features --lib management::tests::authz_matrix_tests::key_issuance_contention_tests::key_issuance_contention_measurement -- --ignored --exact || bad=1
  step integration anthropic-terminal with_db cargo test -p open-model-gateway --all-features --lib providers::anthropic::terminal_tests::terminal_fidelity_official_sdks_and_priced_http_evidence -- --ignored --exact || bad=1
  step integration tools with_loopback_db cargo test --workspace --exclude open-model-gateway --all-features --no-fail-fast || bad=1
  step integration doctests with_db cargo test --workspace --all-features --doc || bad=1
  return "$bad"
}

suite_web() {
  local bad=0
  prepare_npm web || return 1
  extra_args
  step web typecheck npm run typecheck:web || bad=1
  step web vitest npm run test:web -- ${EXTRA[@]+"${EXTRA[@]}"} || bad=1
  return "$bad"
}

main() {
  local started=$SECONDS overall=0 suites
  mark "run suite=$OMG_SUITE commit=$OMG_SHA"
  setup_environment || { mark "setup-failed"; return 1; }
  step setup source prepare_source || { mark "setup-failed"; return 1; }
  step setup toolchain prepare_toolchain || { mark "setup-failed"; return 1; }
  trim_target
  case "$OMG_SUITE" in
    all) suites="web checks lib integration" ;;
    lib | integration | web | checks) suites=$OMG_SUITE ;;
    *) echo "unknown suite $OMG_SUITE"; return 1 ;;
  esac
  for suite in $suites; do
    mark "suite-start suite=$suite"
    "suite_$suite" || overall=1
    mark "suite-end suite=$suite"
  done
  trim_target
  mark "done exit=$overall seconds=$((SECONDS - started))"
  return "$overall"
}

main 2>&1 | redact
exit "${PIPESTATUS[0]}"
