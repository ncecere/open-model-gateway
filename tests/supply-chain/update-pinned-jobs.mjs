// Rewrites tests/supply-chain/pinned-jobs.yaml from the workflows. Run it after a reviewed
// change to a pinned job (node tests/supply-chain/update-pinned-jobs.mjs), then read the diff
// of pinned-jobs.yaml: it is the change to what builds, publishes or tests an image.
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { stringify } from "yaml";
import { root } from "./lib.mjs";
import { PINNED_JOBS_FILE, currentPins } from "./policy.mjs";

const header = `# Generated by tests/supply-chain/update-pinned-jobs.mjs; checked by
# tests/supply-chain/pinned-jobs.test.mjs (#488). Every job that builds, publishes, signs,
# attests, imports or tests an image, exactly as its workflow defines it, and the top-level
# keys of each workflow that holds one. A change to one of these jobs fails the test until
# this file is regenerated, so the change shows here in review. Read it as the diff of what
# runs next to the image under test, not as generated noise.
`;
writeFileSync(join(root, PINNED_JOBS_FILE), header + stringify(currentPins(), { lineWidth: 0, blockQuote: "literal" }));
